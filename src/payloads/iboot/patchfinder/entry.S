.text
.p2align 2

.extern _patchfinder_mmu_enable
.extern _patchfinder_mmu_disable

.globl _start
_start:
    mov x28, lr

    mov x0, x28
    adr x1, _start
    // cacheing + stack setup for the cpp we're about to bl to.
    bl _patchfinder_mmu_enable // ((void*)iboot, (void*)us)
    mov x19, sp
    mov sp, x0

    mov x0, x28
    bl _patchfinder
    mov x20, x0

    mov x0, x28
    bl _patchfinder_mmu_disable

    mov sp, x19
    mov lr, x28
    mov x0, x20
    mov x28, #0
    mov x18, #0
    mov x19, #0
    mov x20, #0
    cbnz x0, __spin
    ret

__spin:
b __spin
