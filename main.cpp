#include "hardware/clocks.h"
#include "hardware/watchdog.h"
#include "pico/stdlib.h"

#include "control/Controller.h"
#include "control/Fault.h"
#include "include/control/LED.h"

int main(void) {
    const bool clock_ok = set_sys_clock_khz(156000, true);

    led::Init();
    led::SetPattern(led::Pattern::Breathe(led::colors::Amber, led::colors::Off, 1600, 72));

    sleep_ms(100);

    if (!clock_ok) {
        led::SetPattern(led::Pattern::Strobe(led::colors::Red, led::colors::Off, 160, 96));
        control::PanicTarget(control::FaultReason::Bug, 0, 0, 156000);
    } else {
        led::SetPattern(led::Pattern::Pulse(led::colors::Blue, led::colors::Off, 2400, 64));
    }

    static control::Controller controller;
    controller.Run();
}

